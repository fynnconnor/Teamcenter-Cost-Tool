#!/usr/bin/env python3
"""Generate derived files from schema/cost_cockpit.schema.json.

- docs/03-data-dictionary.md          human-readable data model (also the manual-build specification)
- scripts/provision_browser_console.js  the same provisioning plan as provision_dataverse.py, runnable
                                        from the browser console of the environment (no installation)
- scripts/load_seed_browser_console.js  the seed data loader for the browser console

Run after every change to the schema file:  python build_artifacts.py
"""
from __future__ import annotations

import json
from pathlib import Path

from load_seed_data import build_operations
from provision_dataverse import DEFAULT_SCHEMA, build_plan

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
TYPE_LABEL = {"text": "Text", "memo": "Multiline text", "decimal": "Decimal", "int": "Whole number", "bool": "Yes/No",
              "date": "Date only", "datetime": "Date and time", "choice": "Choice"}


def data_dictionary(schema: dict) -> str:
    out = ["# Data dictionary", "",
           "Generated from `schema/cost_cockpit.schema.json` by `scripts/build_artifacts.py`. Do not edit by hand.", "",
           f"Publisher prefix `{schema['publisher']['prefix']}` · solution `{schema['solution']['uniquename']}` · "
           f"{len(schema['tables'])} tables · {len(schema['choices'])} global choices.", "",
           "Use this file in two ways: as reference while building apps, flows and reports, and as the specification "
           "if you create the tables by hand in the maker portal instead of running the provisioning script.", "",
           "## Tables at a glance", "", "| Table | Logical name | Purpose | Serves |", "|---|---|---|---|"]
    for t in schema["tables"]:
        out.append(f"| {t['display']} | `{t['schema'].lower()}` | {t['description']} | {' '.join(t['serves'])} |")
    out.append("")
    for t in schema["tables"]:
        logical = t["schema"].lower()
        out += [f"## {t['display']}", "", f"Logical name `{logical}` · plural *{t['plural']}* · ownership {t.get('ownership', 'UserOwned')}.", "",
                t["description"], "", "| Column | Logical name | Type | Required | Notes |", "|---|---|---|---|---|",
                f"| {t['primary']['display']} | `{t['primary']['schema'].lower()}` | Text ({t['primary']['maxlen']}), primary name | Yes | |"]
        for c in t["columns"]:
            typ = TYPE_LABEL[c["type"]]
            if c["type"] == "text":
                typ += f" ({c['maxlen']})"
            elif c["type"] == "decimal":
                typ += f" ({c['precision']} decimals)"
            elif c["type"] == "choice":
                typ += f": {schema['choices'][c['choice']]['label']}"
            out.append(f"| {c['display']} | `{c['schema'].lower()}` | {typ} | {'Yes' if c.get('required') else 'No'} | {c.get('description', '')} |")
        for lk in t["lookups"]:
            out.append(f"| {lk['display']} | `{lk['schema'].lower()}` | Lookup to `{lk['target']}` | {'Yes' if lk.get('required') else 'No'} | "
                       f"On delete of the parent: {lk.get('delete', 'RemoveLink')}. Navigation property `{lk['schema']}`. |")
        out.append("")
        if t["keys"]:
            out.append("Alternate keys: " + "; ".join(f"**{k['display']}** on " + ", ".join(f"`{c}`" for c in k["columns"]) for k in t["keys"]) + ".")
            out.append("")
        if t.get("formulas"):
            out += ["Formula columns (create by hand, data type *fx Formula*; set the schema name under *Advanced options* before saving):", "",
                    "| Column | Schema name | Result type | Decimals | Formula |", "|---|---|---|---|---|"]
            for f in t["formulas"]:
                out.append(f"| {f['display']} | `{f['schema']}` | {f['datatype']} | {f['decimals']} | `{f['formula']}` |")
            out.append("")
    out += ["## Global choices", "", "Flows and the Web API use the numeric values; apps and reports show the labels.", ""]
    for name, ch in schema["choices"].items():
        out += [f"### {ch['label']} (`{name}`)", "", "| Value | Label |", "|---|---|"]
        out += [f"| {o['value']} | {o['label']} |" for o in ch["options"]]
        out.append("")
    return "\n".join(out)


JS_TEMPLATE = r"""/* Cost Cockpit - create the Dataverse data model from the browser console.
 *
 * Generated by scripts/build_artifacts.py from schema/cost_cockpit.schema.json. Do not edit by hand.
 *
 * How to use
 *   1. Open any model-driven app or https://<org>.crm4.dynamics.com/main.aspx in Edge or Chrome while signed in.
 *      You need the System Customizer or System Administrator role in that environment.
 *   2. Press F12, open the Console tab, paste this whole file and press Enter.
 *   3. Watch the log. The script is idempotent: existing objects are skipped, so it can be run again.
 *   Set CHECK_ONLY = true to only report what exists and what is missing.
 *
 * The script calls the Dataverse Web API of the environment you are signed in to, with your own permissions.
 * It sends nothing anywhere else.
 */
(async () => {
  const CHECK_ONLY = false;
  const SOLUTION = __SOLUTION__;
  const API = "/api/data/v9.2/";
  const PLAN = __PLAN__;

  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  async function call(method, path, body, inSolution) {
    const headers = { "Accept": "application/json", "OData-MaxVersion": "4.0", "OData-Version": "4.0" };
    if (body !== undefined) headers["Content-Type"] = "application/json; charset=utf-8";
    if (inSolution) headers["MSCRM.SolutionUniqueName"] = SOLUTION;
    for (let attempt = 0; attempt < 6; attempt++) {
      const resp = await fetch(API + encodeURI(path), { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
      if ((resp.status === 429 || resp.status === 503) && attempt < 5) {
        const wait = parseInt(resp.headers.get("Retry-After") || "5", 10);
        console.log("    service protection limit, waiting " + wait + "s");
        await sleep(wait * 1000);
        continue;
      }
      const text = await resp.text();
      let json = null;
      try { json = text ? JSON.parse(text) : null; } catch (e) { json = text; }
      return { status: resp.status, json, entityId: resp.headers.get("OData-EntityId") || "" };
    }
    throw new Error("retries exhausted");
  }
  const errText = (j) => (j && j.error && j.error.message ? j.error.message : JSON.stringify(j)).slice(0, 400);

  async function exists(step) {
    const r = await call("GET", step.exists);
    if (step.exists_mode === "single") {
      if (r.status === 200) return { found: true, row: r.json };
      const msg = JSON.stringify(r.json || "").toLowerCase();
      if (r.status === 404 || (r.status === 400 && (msg.includes("does not exist") || msg.includes("could not find")))) return { found: false };
      throw new Error("Unexpected answer " + r.status + " while checking " + step.name + ": " + errText(r.json));
    }
    if (r.status !== 200) {
      if (step.exists_mode === "key-list" && r.status === 404) return { found: false };
      throw new Error("Unexpected answer " + r.status + " while checking " + step.name + ": " + errText(r.json));
    }
    const values = (r.json && r.json.value) || [];
    if (step.exists_mode === "collection") return { found: values.length > 0, row: values[0] };
    return { found: values.some((v) => (v.SchemaName || "").toLowerCase() === step.key_schema.toLowerCase()) };
  }

  const who = await call("GET", "WhoAmI");
  if (who.status !== 200) { console.error("Not connected to a Dataverse environment: HTTP " + who.status); return; }
  console.log("Connected as user " + who.json.UserId + ". " + PLAN.length + " objects to process.");
  let created = 0, skipped = 0, missing = 0, failed = 0, publisherId = null;
  for (const step of PLAN) {
    let e;
    try { e = await exists(step); } catch (err) { console.error("  ERROR   " + step.kind + " " + step.name + ": " + err.message); failed++; continue; }
    if (step.kind === "publisher" && e.found) publisherId = e.row.publisherid;
    if (e.found) { skipped++; console.log("  exists  " + step.kind + " " + step.name); continue; }
    if (CHECK_ONLY) { missing++; console.warn("  MISSING " + step.kind + " " + step.name); continue; }
    let body = step.body;
    if (step.kind === "solution") {
      if (!publisherId) { console.error("  ERROR   solution: publisher id unknown"); failed++; continue; }
      body = Object.assign({}, body, { "publisherid@odata.bind": "/publishers(" + publisherId + ")" });
    }
    const r = await call("POST", step.post, body, step.in_solution);
    if ([200, 201, 204].includes(r.status)) {
      created++; console.log("  created " + step.kind + " " + step.name);
      if (step.kind === "publisher") {
        publisherId = r.entityId.slice(r.entityId.lastIndexOf("(") + 1, r.entityId.lastIndexOf(")")) || null;
        if (!publisherId) { const again = await exists(step); publisherId = again.row ? again.row.publisherid : null; }
      }
    } else {
      failed++;
      (step.optional ? console.warn : console.error)("  " + (step.optional ? "WARN" : "ERROR") + "    " + step.kind + " " + step.name + ": HTTP " + r.status + " " + errText(r.json));
    }
  }
  if (!CHECK_ONLY && created > 0) {
    const p = await call("POST", "PublishAllXml", {});
    console.log([200, 204].includes(p.status) ? "  published all customizations" : "  WARN publish failed: HTTP " + p.status);
  }
  console.log("Summary: " + created + " created, " + skipped + " already existed, " + missing + " missing, " + failed + " failed");
  console.log("Formula columns are not created by this script; see docs/03-data-dictionary.md.");
})();
"""


SEED_JS_TEMPLATE = r"""/* Cost Cockpit - load the seed and demo data from the browser console.
 *
 * Generated by scripts/build_artifacts.py from the CSV files in seed/. Do not edit by hand.
 * All cost figures are synthetic demo values.
 *
 * Run it like provision_browser_console.js: open the environment, press F12, paste into the Console, press Enter.
 * Run the provisioning script first and wait a few minutes until the alternate keys are active.
 * Rows are upserted, so the script can be run again.
 */
(async () => {
  const API = "/api/data/v9.2/";
  const OPS = __OPS__;
  const H = { "Accept": "application/json", "OData-MaxVersion": "4.0", "OData-Version": "4.0", "Content-Type": "application/json; charset=utf-8" };
  const q = (v) => "'" + String(v).replace(/'/g, "''") + "'";
  async function call(method, path, body) {
    const resp = await fetch(API + encodeURI(path), { method, headers: H, body: body === undefined ? undefined : JSON.stringify(body) });
    const text = await resp.text();
    let json = null;
    try { json = text ? JSON.parse(text) : null; } catch (e) { json = text; }
    return { status: resp.status, json };
  }
  const names = new Set();
  OPS.forEach((o) => { names.add(o.table); o.binds.forEach((b) => names.add(b.target)); });
  const sets = {};
  for (const n of names) {
    const r = await call("GET", "EntityDefinitions(LogicalName='" + n + "')?$select=EntitySetName");
    if (r.status !== 200) { console.error("Table " + n + " not found. Run the provisioning script first."); return; }
    sets[n] = r.json.EntitySetName;
  }
  let done = 0, failed = 0;
  for (const op of OPS) {
    const body = Object.assign({}, op.body);
    op.binds.forEach((b) => { body[b.nav + "@odata.bind"] = "/" + sets[b.target] + "(" + b.key_col + "=" + q(b.value) + ")"; });
    const target = sets[op.table];
    let r;
    if (op.key) {
      r = await call("PATCH", target + "(" + op.key.col + "=" + q(op.key.value) + ")", body);
    } else {
      const m = op.match_name;
      r = await call("GET", target + "?$select=" + m.id_col + "&$filter=" + m.col + " eq " + q(m.value) + "&$top=1");
      if (r.status === 200 && r.json.value.length) r = await call("PATCH", target + "(" + r.json.value[0][m.id_col] + ")", body);
      else if (r.status === 200) r = await call("POST", target, body);
    }
    if ([200, 201, 204].includes(r.status)) done++;
    else { failed++; console.error("  ERROR " + op.file + " line " + op.line + ": HTTP " + r.status + " " + JSON.stringify(r.json).slice(0, 300)); }
  }
  console.log("Seed data: " + done + " rows written, " + failed + " failed");
})();
"""


def main() -> None:
    schema = json.loads(Path(DEFAULT_SCHEMA).read_text(encoding="utf-8"))
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "03-data-dictionary.md").write_text(data_dictionary(schema), encoding="utf-8")
    plan = build_plan(schema)
    js = JS_TEMPLATE.replace("__SOLUTION__", json.dumps(schema["solution"]["uniquename"])).replace(
        "__PLAN__", json.dumps(plan, ensure_ascii=False, separators=(",", ":")))
    (HERE / "provision_browser_console.js").write_text(js, encoding="utf-8")
    ops = build_operations(schema)
    (HERE / "load_seed_browser_console.js").write_text(
        SEED_JS_TEMPLATE.replace("__OPS__", json.dumps(ops, ensure_ascii=False, separators=(",", ":"))), encoding="utf-8")
    print(f"data dictionary and console scripts written ({len(plan)} plan steps, {len(ops)} seed rows)")


if __name__ == "__main__":
    main()
